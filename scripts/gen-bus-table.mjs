// The bus table in docs/engineering/entities.md, generated from the code (ADR 0027).
//
// The table used to be written by hand, and by October 2026 it listed 7 of the
// catalogue's 49 events: a reader looking for who hears `board.card.completed`
// found coaching alone, when ideas, ladders and notifications heard it too.
// The catalogue in kernel/events/catalogue*.ts is the list of events, so the
// table is derived from it, with each event's publishers and subscribers read
// from the source.
//
// Two rules, each with a planted violation in scripts/gen-bus-table.test.mjs:
//   1. The table between the `bus-table` markers is exactly what this script
//      writes: one row per catalogue event, its publishers (entities whose code
//      calls `publish("<event>"` or an `announce("<event>"` wrapper, and the
//      outbox when a migration inserts the event into company_os.event_outbox),
//      and the entities that `subscribe(…, "<event>"`.
//   2. The hand-written table between the `bus-replays` markers names every
//      entity that subscribes to anything, and no other. ADR 0027 says a new
//      subscriber is reviewed for idempotency and for whether it needs a replay;
//      this is where that review is written down, so a subscriber nobody
//      reviewed fails here.
//
// Blind spots, said rather than hidden: a publish whose event name is not a
// literal at the call (a variable, a template string) is not seen, nor is a
// subscription registered through a helper other than `subscribe`. The table
// then shows "—" for that event's publisher, which a reader will notice.
//
//   node scripts/gen-bus-table.mjs                 rewrite the table in this repository
//   node scripts/gen-bus-table.mjs --check         fail when either rule is broken
//   node scripts/gen-bus-table.mjs --root <dir>    another tree (the fires test's fixtures)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { isForkTree, skippedInFork } from "./fork-tree.mjs";

const args = process.argv.slice(2);
const rootAt = args.indexOf("--root");
const root =
  rootAt === -1 ? path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..") : path.resolve(args[rootAt + 1] ?? ".");
const check = args.includes("--check");

const DOC = "docs/engineering/entities.md";
const TABLE_BEGIN = "<!-- bus-table:begin (generated by npm run gen:bus-table from kernel/events/catalogue*.ts; do not edit) -->";
const TABLE_END = "<!-- bus-table:end -->";
const REPLAYS_BEGIN = "<!-- bus-replays:begin (hand-written; npm run check:bus-table fails when it misses a subscriber) -->";
const REPLAYS_END = "<!-- bus-replays:end -->";

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/\.tsx?$/.test(e.name) && !/\.test\.tsx?$/.test(e.name)) out.push(p);
  }
  return out;
}

/** The catalogue's event names, sorted so a reader finds one by name. Keys sit at two spaces in the EVENTS objects. */
function catalogue() {
  const dir = path.join(root, "kernel/events");
  const files = fs.readdirSync(dir).filter((f) => /^catalogue.*\.ts$/.test(f) && !f.endsWith(".test.ts")).sort();
  const names = [];
  for (const f of files) {
    for (const m of fs.readFileSync(path.join(dir, f), "utf8").matchAll(/^ {2}"([^"]+)":/gm)) names.push(m[1]);
  }
  return names.sort();
}

/** event -> Set of publishers, event -> Set of subscribers, read from entities/ and kernel/ and the migrations. */
function wiring() {
  const publishers = new Map();
  const subscribers = new Map();
  const add = (map, key, value) => map.set(key, (map.get(key) ?? new Set()).add(value));
  for (const file of [...walk(path.join(root, "entities")), ...walk(path.join(root, "kernel"))]) {
    const rel = path.relative(root, file).split(path.sep);
    const owner = rel[0] === "entities" ? rel[1] : "kernel";
    const text = fs.readFileSync(file, "utf8");
    for (const m of text.matchAll(/\b(?:publish|announce)\(\s*"([^"]+)"/g)) add(publishers, m[1], owner);
    for (const m of text.matchAll(/\bsubscribe\(\s*"([^"]+)",\s*"([^"]+)"/g)) add(subscribers, m[2], m[1]);
  }
  const migrations = path.join(root, "supabase/migrations");
  if (fs.existsSync(migrations)) {
    for (const f of fs.readdirSync(migrations).filter((n) => n.endsWith(".sql"))) {
      const sql = fs.readFileSync(path.join(migrations, f), "utf8");
      for (const m of sql.matchAll(/insert\s+into\s+company_os\.event_outbox[\s\S]{0,300}?'([a-z0-9_.-]+)'/gi)) add(publishers, m[1], "the outbox");
    }
  }
  return { publishers, subscribers };
}

const list = (set) => (set && set.size > 0 ? [...set].sort((a, b) => (a === "the outbox") - (b === "the outbox") || a.localeCompare(b)).join(", ") : "—");

function renderTable(names, { publishers, subscribers }) {
  const rows = names.map((n) => `| \`${n}\` | ${list(publishers.get(n))} | ${list(subscribers.get(n))} |`);
  return [TABLE_BEGIN, "| Event | Published by | Heard by |", "|---|---|---|", ...rows, TABLE_END].join("\n");
}

function between(doc, begin, end) {
  const a = doc.indexOf(begin);
  const b = doc.indexOf(end);
  if (a === -1 || b === -1 || b < a) return null;
  return { start: a, stop: b + end.length, body: doc.slice(a + begin.length, b) };
}

const docPath = path.join(root, DOC);
// The fork is sent no docs/engineering/ (.github/fork-sync-exclude.txt), so
// there is no table there to keep. Here the document must exist.
if (isForkTree(root) && !fs.existsSync(docPath)) {
  skippedInFork("check:bus-table", `${DOC} is not sent to the fork`);
  process.exit(0);
}
const doc = fs.readFileSync(docPath, "utf8");
const names = catalogue();
const wired = wiring();
const table = renderTable(names, wired);
const errors = [];

const current = between(doc, TABLE_BEGIN, TABLE_END);
if (!current) errors.push(`${DOC} has no bus table between the markers:\n  ${TABLE_BEGIN}\n  ${TABLE_END}`);

// Every event a publisher or subscriber names must be in the catalogue; bus.ts
// refuses anything else at run time, so a name here outside it is a typo the
// type checker missed (a test fake, a string built elsewhere).
for (const map of [wired.publishers, wired.subscribers]) {
  for (const name of map.keys()) if (!names.includes(name)) errors.push(`"${name}" is published or subscribed to but is not in kernel/events/catalogue*.ts`);
}

const replays = between(doc, REPLAYS_BEGIN, REPLAYS_END);
const subscribing = new Set([...wired.subscribers.values()].flatMap((s) => [...s]));
if (!replays) {
  errors.push(`${DOC} has no subscriber replay table between the markers:\n  ${REPLAYS_BEGIN}\n  ${REPLAYS_END}`);
} else {
  const reviewed = new Set([...replays.body.matchAll(/^\|\s*`([a-z0-9-]+)`\s*\|/gm)].map((m) => m[1]));
  for (const e of [...subscribing].sort()) {
    if (!reviewed.has(e)) errors.push(`${e} subscribes to the bus but has no row in the subscriber replay table: say whether its handlers are idempotent and what replays a failed one (ADR 0027)`);
  }
  for (const e of [...reviewed].sort()) {
    if (!subscribing.has(e)) errors.push(`${e} has a row in the subscriber replay table but subscribes to nothing`);
  }
}

if (check) {
  if (current && current.body.trim() !== table.slice(TABLE_BEGIN.length, -TABLE_END.length).trim()) {
    errors.push(`the bus table in ${DOC} differs from the catalogue and the code. Run: npm run gen:bus-table`);
  }
  if (errors.length > 0) {
    console.error(`check:bus-table: ${errors.length} problem(s)\n- ${errors.join("\n- ")}`);
    process.exit(1);
  }
  console.log(`check:bus-table: ${names.length} event(s) in the table, ${subscribing.size} subscribing entit(ies) reviewed`);
} else {
  if (!current) {
    console.error(errors.join("\n"));
    process.exit(1);
  }
  fs.writeFileSync(docPath, doc.slice(0, current.start) + table + doc.slice(current.stop));
  const rest = errors.filter((e) => !e.includes("no bus table"));
  if (rest.length > 0) console.warn(`gen:bus-table wrote the table; still to fix:\n- ${rest.join("\n- ")}`);
  else console.log(`gen:bus-table: ${names.length} event(s) written to ${DOC}`);
}
