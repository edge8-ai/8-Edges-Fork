// The "fires" test for scripts/gen-bus-table.mjs (ADR 0033): its entry point is
// run with `--root` over a fixture tree holding one planted violation per rule
// its header claims, and over a clean twin that must pass. The CLI never runs
// against the working directory: git hooks export GIT_DIR, and a test that
// leans on the cwd can end up reading the real repository.

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";

const SCRIPT = path.join(path.dirname(fileURLToPath(import.meta.url)), "gen-bus-table.mjs");
const TABLE_BEGIN = "<!-- bus-table:begin (generated by npm run gen:bus-table from kernel/events/catalogue*.ts; do not edit) -->";
const TABLE_END = "<!-- bus-table:end -->";
const REPLAYS_BEGIN = "<!-- bus-replays:begin (hand-written; npm run check:bus-table fails when it misses a subscriber) -->";
const REPLAYS_END = "<!-- bus-replays:end -->";

const CLEAN_TABLE = [
  "| Event | Published by | Heard by |",
  "|---|---|---|",
  "| `deal.won` | crm | boards |",
  "| `hire.made` | hiring, the outbox | onboarding |",
  "| `quest.closed` | quests | — |",
].join("\n");
const CLEAN_REPLAYS = [
  "| Subscriber | What it does | Idempotent? | Replay | Cost |",
  "|---|---|---|---|---|",
  "| `boards` | opens a board | yes | none | 1 ms |",
  "| `onboarding` | opens a journey | yes | backfill | 1 ms |",
].join("\n");

const tmpDirs = [];
function write(root, rel, text) {
  fs.mkdirSync(path.join(root, path.dirname(rel)), { recursive: true });
  fs.writeFileSync(path.join(root, rel), text);
}
function fixture({ table = CLEAN_TABLE, replays = CLEAN_REPLAYS, extra = {} } = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "gen-bus-table-"));
  tmpDirs.push(root);
  write(root, "kernel/events/catalogue.ts", 'export const EVENTS = {\n  "deal.won": z.object({}),\n  "quest.closed": z.object({}),\n  "hire.made": z.object({}),\n};\n');
  write(root, "entities/crm/lib/stages.ts", 'await publish("deal.won", { dealId });\n');
  write(root, "entities/quests/lib/clock.ts", 'await announce("quest.closed", { questId });\n');
  write(root, "entities/hiring/lib/decide.ts", 'await publish("hire.made", payload);\n');
  // A test file's publish is not a publisher.
  write(root, "entities/team/lib/stages.test.ts", 'await publish("deal.won", {});\n');
  write(root, "entities/boards/lib/subscriptions.ts", 'subscribe("boards", "deal.won", openBoards);\n');
  write(root, "entities/onboarding/lib/subscriptions.ts", 'subscribe("onboarding", "hire.made", openJourney);\n');
  write(root, "supabase/migrations/20261009200000_hiring.sql", "insert into company_os.event_outbox (event_name, dedupe_key, payload)\nvalues (\n  'hire.made',\n  p_id::text,\n  '{}'::jsonb);\n");
  for (const [rel, text] of Object.entries(extra)) write(root, rel, text);
  write(
    root,
    "docs/engineering/entities.md",
    `# Entities\n\n${TABLE_BEGIN}\n${table}\n${TABLE_END}\n\nprose\n\n${REPLAYS_BEGIN}\n${replays}\n${REPLAYS_END}\n`,
  );
  return root;
}
function run(root, ...flags) {
  const env = { ...process.env };
  delete env.GIT_DIR;
  delete env.GIT_WORK_TREE;
  return spawnSync(process.execPath, [SCRIPT, "--root", root, ...flags], { encoding: "utf8", env });
}
afterEach(() => {
  for (const dir of tmpDirs.splice(0)) fs.rmSync(dir, { recursive: true, force: true });
});

describe("gen-bus-table fires", () => {
  it("passes a clean tree: every catalogue event has its row, and every subscriber its replay row", () => {
    const res = run(fixture(), "--check");
    expect(res.status, res.stderr).toBe(0);
    expect(res.stdout).toContain("3 event(s) in the table, 2 subscribing entit(ies) reviewed");
  });

  it("rule 1: fails a table that has drifted from the catalogue, and writing it makes the twin pass", () => {
    const stale = CLEAN_TABLE.replace("| `deal.won` | crm | boards |", "| `deal.won` | crm | boards, coaching |").replace(
      "| `quest.closed` | quests | — |\n",
      "",
    );
    const root = fixture({ table: stale });
    const planted = run(root, "--check");
    expect(planted.status).toBe(1);
    expect(planted.stderr).toContain("the bus table in docs/engineering/entities.md differs from the catalogue and the code");

    expect(run(root).status).toBe(0);
    const written = fs.readFileSync(path.join(root, "docs/engineering/entities.md"), "utf8");
    expect(written).toContain(CLEAN_TABLE);
    expect(run(root, "--check").status).toBe(0);
  });

  it("rule 1: fails an event published or heard that is not in the catalogue", () => {
    const res = run(fixture({ extra: { "entities/crm/lib/typo.ts": 'await publish("deal.wom", {});\n' } }), "--check");
    expect(res.status).toBe(1);
    expect(res.stderr).toContain('"deal.wom" is published or subscribed to but is not in kernel/events/catalogue*.ts');
  });

  it("rule 2: fails a subscriber with no replay row, and a replay row for an entity that subscribes to nothing", () => {
    const res = run(
      fixture({
        replays: CLEAN_REPLAYS.replace("| `onboarding` | opens a journey | yes | backfill | 1 ms |", "| `coaching` | gone | yes | none | 1 ms |"),
      }),
      "--check",
    );
    expect(res.status).toBe(1);
    expect(res.stderr).toContain("onboarding subscribes to the bus but has no row in the subscriber replay table");
    expect(res.stderr).toContain("coaching has a row in the subscriber replay table but subscribes to nothing");
  });

  it("stands down in the fork, which is sent no docs/engineering/, and fails a missing document anywhere else", () => {
    const fork = fixture({ extra: { "supabase/01-schema.sql": "-- the fork's schema\n" } });
    fs.rmSync(path.join(fork, "docs"), { recursive: true });
    const skipped = run(fork, "--check");
    expect(skipped.status, skipped.stderr).toBe(0);
    expect(skipped.stdout).toContain("check:bus-table: nothing to check in the fork");

    const upstream = fixture();
    fs.rmSync(path.join(upstream, "docs"), { recursive: true });
    expect(run(upstream, "--check").status).not.toBe(0);
  });

  it("fails a document that lost its markers rather than passing an empty check", () => {
    const root = fixture();
    write(root, "docs/engineering/entities.md", "# Entities\n\nno tables here\n");
    const res = run(root, "--check");
    expect(res.status).toBe(1);
    expect(res.stderr).toContain("has no bus table between the markers");
    expect(res.stderr).toContain("has no subscriber replay table between the markers");
  });
});
